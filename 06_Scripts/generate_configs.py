def ap_plan():
    mgmt = {name: ip for name, _, ip, _ in P.STATIC_ASSIGNMENTS}
    ports = {"AP-ENG": "Gi1/0/24", "AP-STAFF": "Gi1/0/25", "AP-MGMT": "Gi1/0/26"}
    channels = {
        "AP-ENG": ("36", "1", "Engineering / east wing"),
        "AP-STAFF": ("44", "6", "Conference / reception / staff"),
        "AP-MGMT": ("149", "11", "Management / HR / west wing"),
    }
    lines = [
        "NEXASOFT OFFICE LAN - AP DEPLOYMENT PLAN",
        "=" * 64,
        "Controller mode: autonomous / embedded controller",
        "Management VLAN: 99 (192.168.10.192/28); gateway 192.168.10.193",
        "AP trunks: native VLAN 99; AP-ENG allows 20,30,40,99; other APs allow 20,40,99",
        "PoE: 802.3at; WPA2-AES; management SSID not broadcast",
        "",
    ]
    for name in ("AP-ENG", "AP-STAFF", "AP-MGMT"):
        five, two, area = channels[name]
        x, y, _ = P.AP_POSITIONS[name]
        ssids = ["  NEXA-STAFF  -> VLAN 20  WPA2-AES  (staff devices)",
                 "  NEXA-GUEST  -> VLAN 40  WPA2-AES  client isolation enabled"]
        if name == "AP-ENG":
            ssids.insert(0, "  NEXA-ENG    -> VLAN 30  WPA2-AES  (engineering devices)")
        lines.extend([
            name,
            "-" * len(name),
            f"Management IP: {mgmt[name]}/28",
            f"Ceiling position: ({x}, {y}) ft; coverage area: {area}",
            f"Switch port: NXS-CORE-SW {ports[name]} "
            f"({'trunk 20,30,40,99' if name == 'AP-ENG' else 'trunk 20,40,99'})",
            f"2.4 GHz channel: {two}; 5 GHz channel: {five}; power: auto",
            "SSIDs:",
        ] + ssids + [""])
    lines.extend([
        "Guest policy: internet-only; GUEST-IN ACL blocks 192.168.10.0/24.",
        "Staff policy: internal access; VLAN 20/30 denied to management VLAN 99.",
        "Guest DHCP DNS: 8.8.8.8; staff and engineering DHCP DNS: 192.168.10.10.",
        "SSH management: only 192.168.10.192/28 may reach the AP management GUI/CLI.",
    ])
    return "\n".join(lines) + "\n"


