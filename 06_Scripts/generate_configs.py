    (CONFIG_DIR / "NXS-GW.cfg").write_text(router_config(), encoding="utf-8")
    (CONFIG_DIR / "NXS-CORE-SW.cfg").write_text(core_config(), encoding="utf-8")
    (CONFIG_DIR / "NXS-ENG-SW.cfg").write_text(access_config(), encoding="utf-8")
    (CONFIG_DIR / "AP_SSID_Plan.txt").write_text(ap_plan(), encoding="utf-8")
    with (CONFIG_DIR / "PORT_MAP.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle)
        writer.writerow(["switch", "port", "connected_device", "mode", "vlan", "notes"])
        writer.writerows(port_map_rows())
    print("wrote", CONFIG_DIR / "NXS-GW.cfg")
    print("wrote", CONFIG_DIR / "NXS-CORE-SW.cfg")
    print("wrote", CONFIG_DIR / "NXS-ENG-SW.cfg")
    print("wrote", CONFIG_DIR / "AP_SSID_Plan.txt")
    print("wrote", CONFIG_DIR / "PORT_MAP.csv")


